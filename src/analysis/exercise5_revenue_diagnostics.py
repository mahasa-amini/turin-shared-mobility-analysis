# REVENUE PER TRIP DISTRIBUTION
# =============================================================================

def build_trip_distribution(df):

    rows = []

    estimable = df.loc[
        df[
            "revenue_duration_estimable"
        ]
    ].copy()

    for operator, group in (
        estimable.groupby(
            "operator",
            observed=True,
        )
    ):

        values = group[
            "gross_payg_continuous_eur"
        ]

        rows.append(
            {
                "operator":
                    operator,

                "trips":
                    len(group),

                "mean_revenue_per_trip_eur":
                    values.mean(),

                "median_revenue_per_trip_eur":
                    values.median(),

                "p10_revenue_per_trip_eur":
                    values.quantile(0.10),

                "p25_revenue_per_trip_eur":
                    values.quantile(0.25),

                "p75_revenue_per_trip_eur":
                    values.quantile(0.75),

                "p90_revenue_per_trip_eur":
                    values.quantile(0.90),

                "p95_revenue_per_trip_eur":
                    values.quantile(0.95),

                "p99_revenue_per_trip_eur":
                    values.quantile(0.99),

                "max_revenue_per_trip_eur":
                    values.max(),
            }
        )

    return pd.DataFrame(rows)


