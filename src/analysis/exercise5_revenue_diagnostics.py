# ACTIVE VEHICLE-DAY ANALYSIS
#
# Feb-Dec 2024 common detailed-temporal window
# =============================================================================

def build_active_vehicle_day_metrics(
    revenue,
    temporal,
):

    data = revenue.merge(
        temporal,
        on="trip_uid",
        how="left",
        validate="one_to_one",
    )

    common = data.loc[
        (
            data[
                "start_time_local"
            ]
            >= COMMON_START
        )
        &
        (
            data[
                "start_time_local"
            ]
            <
            COMMON_END_EXCLUSIVE
        )
    ].copy()

    common[
        "activity_date"
    ] = (
        common[
            "start_time_local"
        ]
        .dt.normalize()
    )

    vehicle_day = (
        common.groupby(
            [
                "operator",
                "vehicle_uid",
                "activity_date",
            ],
            observed=True,
        )
        .agg(
            trips=(
                "trip_uid",
                "count",
            ),

            estimated_payg_revenue_eur=(
                "payg_continuous_lower_bound_eur",
                "sum",
            ),
        )
        .reset_index()
    )

    vehicle = (
        vehicle_day.groupby(
            [
                "operator",
                "vehicle_uid",
            ],
            observed=True,
        )
        .agg(
            active_days=(
                "activity_date",
                "nunique",
            ),

            common_window_trips=(
                "trips",
                "sum",
            ),

            common_window_revenue_eur=(
                "estimated_payg_revenue_eur",
                "sum",
            ),
        )
        .reset_index()
    )

    vehicle[
        "revenue_per_active_vehicle_day_eur"
    ] = (
        vehicle[
            "common_window_revenue_eur"
        ]
        /
        vehicle[
            "active_days"
        ]
    )

    vehicle[
        "trips_per_active_vehicle_day"
    ] = (
        vehicle[
            "common_window_trips"
        ]
        /
        vehicle[
            "active_days"
        ]
    )

    summary_rows = []

    for operator, group in (
        vehicle.groupby(
            "operator",
            observed=True,
        )
    ):

        total_active_days = (
            group[
                "active_days"
            ]
            .sum()
        )

        total_revenue = (
            group[
                "common_window_revenue_eur"
            ]
            .sum()
        )

        total_trips = (
            group[
                "common_window_trips"
            ]
            .sum()
        )

        summary_rows.append(
            {
                "operator":
                    operator,

                "common_window":
                    "2024-02-01_to_2024-12-31",

                "vehicles_observed_in_common_window":
                    group[
                        "vehicle_uid"
                    ]
                    .nunique(),

                "total_active_vehicle_days":
                    total_active_days,

                "common_window_trips":
                    total_trips,

                "common_window_revenue_eur":
                    total_revenue,

                "revenue_per_active_vehicle_day_eur":
                    (
                        total_revenue
                        /
                        total_active_days
                    ),

                "trips_per_active_vehicle_day":
                    (
                        total_trips
                        /
                        total_active_days
                    ),

                "median_vehicle_revenue_per_active_day_eur":
                    group[
                        "revenue_per_active_vehicle_day_eur"
                    ]
                    .median(),

                "median_vehicle_trips_per_active_day":
                    group[
                        "trips_per_active_vehicle_day"
                    ]
                    .median(),
            }
        )

    return (
        vehicle_day,
        vehicle,
        pd.DataFrame(
            summary_rows
        ),
    )


