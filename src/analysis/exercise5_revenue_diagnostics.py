# MONTHLY REVENUE-VOLUME RELATIONSHIP
# =============================================================================

def build_monthly_diagnostics(monthly):

    rows = []

    for operator, group in (
        monthly.groupby(
            "operator",
            observed=True,
        )
    ):

        rows.append(
            {
                "operator":
                    operator,

                "months":
                    len(group),

                "trip_volume_vs_total_revenue_pearson_r":
                    group[
                        "trips"
                    ].corr(
                        group[
                            "estimated_payg_revenue_eur"
                        ]
                    ),

                "mean_duration_vs_revenue_per_trip_pearson_r":
                    group[
                        "mean_duration_min"
                    ].corr(
                        group[
                            "estimated_revenue_per_trip_eur"
                        ]
                    ),

                "min_monthly_revenue_eur":
                    group[
                        "estimated_payg_revenue_eur"
                    ].min(),

                "max_monthly_revenue_eur":
                    group[
                        "estimated_payg_revenue_eur"
                    ].max(),

                "coefficient_of_variation_monthly_revenue":
                    (
                        group[
                            "estimated_payg_revenue_eur"
                        ].std()
                        /
                        group[
                            "estimated_payg_revenue_eur"
                        ].mean()
                    ),
            }
        )

    return pd.DataFrame(rows)


