def build_vehicle_concentration(vehicle):

    rows = []

    for operator, group in (
        vehicle.groupby(
            "operator",
            observed=True,
        )
    ):

        revenue = group[
            "estimated_payg_revenue_eur"
        ]

        rows.append(
            {
                "operator":
                    operator,

                "observed_vehicle_ids":
                    len(group),

                "total_vehicle_revenue_eur":
                    revenue.sum(),

                "mean_revenue_per_vehicle_eur":
                    revenue.mean(),

                "median_revenue_per_vehicle_eur":
                    revenue.median(),

                "p90_revenue_per_vehicle_eur":
                    revenue.quantile(0.90),

                "p95_revenue_per_vehicle_eur":
                    revenue.quantile(0.95),

                "gini_revenue_by_vehicle":
                    gini(revenue),

                "top_10pct_vehicle_revenue_share_pct":
                    top_share(
                        revenue,
                        0.10,
                    ),

                "top_20pct_vehicle_revenue_share_pct":
                    top_share(
                        revenue,
                        0.20,
                    ),
            }
        )

    return pd.DataFrame(rows)


