def gini(values):
    """
    Gini coefficient for non-negative values.
    0 = perfectly equal
    1 = maximally concentrated
    """

    x = np.asarray(values, dtype=float)
    x = x[np.isfinite(x)]
    x = x[x >= 0]

    if len(x) == 0:
        return np.nan

    if np.allclose(x.sum(), 0):
        return 0.0

    x = np.sort(x)

    n = len(x)
    index = np.arange(1, n + 1)

    return (
        np.sum(
            (2 * index - n - 1) * x
        )
        /
        (n * x.sum())
    )


def top_share(values, fraction):
    """
    Share of total revenue generated by the top fraction of vehicles.
    """

    x = pd.Series(values).dropna().astype(float)

    if len(x) == 0 or x.sum() == 0:
        return np.nan

    n_top = max(
        1,
        math.ceil(
            len(x) * fraction
        )
    )

    return (
        x.nlargest(n_top).sum()
        /
        x.sum()
        * 100
    )


