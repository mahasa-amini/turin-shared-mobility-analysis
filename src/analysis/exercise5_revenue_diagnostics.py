def build_monthly_summary(df):

    monthly = (
        df.groupby(
            [
                "operator",
                "source_period",
            ],
            observed=True,
        )
        .agg(
            trips=(
                "trip_uid",
                "count",
            ),

            duration_estimable_trips=(
                "revenue_duration_estimable",
                "sum",
            ),

            mean_duration_min=(
                "duration_min_clean",
                "mean",
            ),

            median_duration_min=(
                "duration_min_clean",
                "median",
            ),

            unlock_revenue_eur=(
                "unlock_revenue_eur",
                "sum",
            ),

            time_revenue_known_eur=(
                "time_revenue_continuous_eur",
                "sum",
            ),

            estimated_payg_revenue_eur=(
                "payg_continuous_lower_bound_eur",
                "sum",
            ),
        )
        .reset_index()
    )

    monthly[
        "estimated_revenue_per_trip_eur"
    ] = (
        monthly[
            "estimated_payg_revenue_eur"
        ]
        /
        monthly[
            "trips"
        ]
    )

    annual_revenue = (
        monthly.groupby(
            "operator",
            observed=True,
        )[
            "estimated_payg_revenue_eur"
        ]
        .transform("sum")
    )

    monthly[
        "share_of_operator_annual_revenue_pct"
    ] = (
        monthly[
            "estimated_payg_revenue_eur"
        ]
        /
        annual_revenue
        * 100
    )

    return monthly


