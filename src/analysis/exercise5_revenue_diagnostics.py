# =============================================================================

def build_revenue_composition(df):

    result = (
        df.groupby(
            "operator",
            observed=True,
        )
        .agg(
            trips=(
                "trip_uid",
                "count",
            ),

            unlock_revenue_eur=(
                "unlock_revenue_eur",
                "sum",
            ),

            time_revenue_known_eur=(
                "time_revenue_continuous_eur",
                "sum",
            ),

            total_payg_estimate_eur=(
                "payg_continuous_lower_bound_eur",
                "sum",
            ),
        )
        .reset_index()
    )

    result[
        "unlock_share_pct"
    ] = (
        result[
            "unlock_revenue_eur"
        ]
        /
        result[
            "total_payg_estimate_eur"
        ]
        * 100
    )

    result[
        "time_share_pct"
    ] = (
        result[
            "time_revenue_known_eur"
        ]
        /
        result[
            "total_payg_estimate_eur"
        ]
        * 100
    )

    total_system = (
        result[
            "total_payg_estimate_eur"
        ]
        .sum()
    )

    result[
        "system_revenue_share_pct"
    ] = (
        result[
            "total_payg_estimate_eur"
        ]
        /
        total_system
        * 100
    )

    return result


