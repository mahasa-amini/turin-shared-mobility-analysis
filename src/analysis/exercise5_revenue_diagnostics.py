def load_revenue():

    if not REVENUE_FILE.exists():
        raise FileNotFoundError(REVENUE_FILE)

    df = pd.read_parquet(
        REVENUE_FILE
    )

    required = {
        "operator",
        "trip_uid",
        "vehicle_uid",
        "source_period",
        "duration_min_clean",
        "revenue_duration_estimable",
        "unlock_revenue_eur",
        "time_revenue_continuous_eur",
        "gross_payg_continuous_eur",
        "payg_continuous_lower_bound_eur",
    }

    missing = required - set(df.columns)

    if missing:
        raise ValueError(
            f"Revenue file missing columns: {sorted(missing)}"
        )

    assert df["trip_uid"].is_unique

    return df


def load_temporal_detail():

    if not HARMONIZED_FILE.exists():
        raise FileNotFoundError(HARMONIZED_FILE)

    df = pd.read_parquet(
        HARMONIZED_FILE,
        columns=[
            "trip_uid",
            "start_time_local",
        ],
    )

    assert df["trip_uid"].is_unique

    df["start_time_local"] = pd.to_datetime(
        df["start_time_local"],
        errors="coerce",
    )

    return df


